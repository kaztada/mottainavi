const base = createStandardCsvAdapter(echizenCityConfig)

/** 品目ごとの注記(itemNotes)は1枚目のカードにだけ付くので、どのカードにも出したい注記は2枚目以降にも添える */
const ALL_CARDS = new Set(["ワイヤー"])

export const echizenCityAdapter: StandardCsvAdapter = {
  ...base,
  parse: (source) =>
    parseStandardCsv(echizenCityConfig, toStandardCsv(source, opts)).map(
      (item) => {
        const note = echizenCityConfig.itemNotes?.[item.name_ja]
        if (!note || !ALL_CARDS.has(item.name_ja)) return item
        return {
          ...item,
          rows: item.rows.map((row, i) =>
            i === 0 ? row : { ...row, note: row.note ? `${note}\n${row.note}` : note }
          ),
        }
      }
    ),
}
