/** convert.ts が参照だけの行に付けた案内(「市の50音事典では、この品目は品目「○○」の案内を…」) */
const REFERENCE_LEAD = /^※もったいナビ注: 市の50音事典では、この品目は品目「.+$/m

/**
 * 注意文言の仕上げ:
 * - 参照だけの行に付けた案内は、どのカードの案内かがすぐ分かるよう先頭に移す
 * - 市の「小型家電対象(表の上参照)」の注意に、「表の上」の説明(回収ボックスなど)を添える
 */
export function finishNotes(items: RawItem[]): RawItem[] {
  return items.map((item) => ({
    ...item,
    rows: item.rows.map((row) => {
      let note = row.note
      if (!note) return row
      const lead = note.match(REFERENCE_LEAD)?.[0]
      if (lead) note = [lead, note.replace(lead + "\n", "").replace(lead, "")].join("\n").trim()
      if (note.includes("小型家電対象(表の上参照)")) note = `${note}\n${KOGATA_NOTE}`
      return { ...row, note }
    }),
  }))
}

const base = createStandardCsvAdapter(hiroshimaCityConfig)

export const hiroshimaCityAdapter: StandardCsvAdapter = {
  ...base,
  parse: (source) =>
    finishNotes(parseStandardCsv(hiroshimaCityConfig, toStandardCsv(source))),
}
