const base = createStandardCsvAdapter(inazawaCityConfig)
const XLSX_CACHE = join(CACHE_DIR, "inazawa-city.xlsx")
const CSV_CACHE = join(CACHE_DIR, "inazawa-city.csv")

export const inazawaCityAdapter: StandardCsvAdapter = {
  ...base,
  async fetchSource({ refresh }) {
    const { data, fromCache } = await fetchBinaryWithCache(
      readSource("inazawa-city").file_url,
      XLSX_CACHE,
      refresh
    )
    const source = await xlsxToStandardCsv(data)
    await writeFile(CSV_CACHE, source, "utf-8")
    return { source, fromCache, location: XLSX_CACHE }
  },
  parse: (source) => parseStandardCsv(inazawaCityConfig, source),
}
