/** 収集しない区分の品目の「市では収集しません。」を「区では収集しません。」にする */
function toWard(items: RawItem[]): RawItem[] {
  return items.map((item) => ({
    ...item,
    rows: item.rows.map((row) => ({
      ...row,
      note:
        row.note?.replace(NOT_COLLECTED_NOTE, NOT_COLLECTED_NOTE_KU) ?? null,
    })),
  }))
}

const base = createStandardCsvAdapter(nakanoKuConfig)

export const nakanoKuAdapter: StandardCsvAdapter = {
  ...base,
  parse: (source) =>
    toWard(parseStandardCsv(nakanoKuConfig, toStandardCsv(source))),
}
