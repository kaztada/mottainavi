/** 収集しない区分の品目の「市では収集しません。」を「町では収集しません。」にする */
const toTown = (items: ReturnType<typeof parseStandardCsv>) =>
  items.map((item) => ({
    ...item,
    rows: item.rows.map((row) => ({
      ...row,
      note:
        row.note?.replace(NOT_COLLECTED_NOTE, NOT_COLLECTED_NOTE_TOWN) ?? null,
    })),
  }))

const base = createStandardCsvAdapter(tsubataTownConfig)

export const tsubataTownAdapter: StandardCsvAdapter = {
  ...base,
  parse: (source) =>
    toTown(parseStandardCsv(tsubataTownConfig, toStandardCsv(source))),
}
