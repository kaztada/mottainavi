/** 区分名の後ろの読み仮名の断片 */
const LABEL_FRAGMENTS = ["コガタカデンヒンモク", "ソダイ"]

const quote = (s: string) => `"${s.replace(/"/g, '""')}"`

/** 品目名: 一覧にある読み仮名の断片を取る */
export function cleanName(raw: string): string {
  const name = raw.trim()
  const frag = NAME_FRAGMENTS.get(name)
  if (frag && name.endsWith(frag)) return name.slice(0, -frag.length).trim()
  return name
}

/** 区分名: 【】の中だけにする(後ろの読み仮名の断片も取る) */
export function cleanLabel(raw: string): string {
  const m = raw.trim().match(/^【([^】]+)】(.*)$/)
  if (!m) return raw.trim()
  const rest = m[2].trim()
  if (rest && !LABEL_FRAGMENTS.includes(rest)) {
    throw new Error(`宇部市Excelの区分名の後ろに知らない文字があります: ${raw}`)
  }
  return m[1].trim()
}

/** 出し方: 画面の飾り(♻・🚮注意事項)と、一覧にある末尾の読み仮名の断片を取る。改行コードもそろえる */
export function cleanNote(raw: string, name: string): string {
  let note = raw
    .replace(/\r\n?/g, "\n")
    .replace(/^\s*♻\s*/u, "")
    .replace(/^🚮注意事項[\s　]*/u, "")
    .trim()
  const frag = NOTE_FRAGMENTS.get(name)
  if (frag && note.endsWith(frag)) note = note.slice(0, -frag.length).trim()
  if (/[♻🚮]/u.test(note)) {
    throw new Error(
      `宇部市Excelの出し方に画面の飾りが残っています(${name}): ${note.slice(0, 40)}`
    )
  }
  return note
}

/** Excel のバイト列 → 標準形式の CSV テキスト */
export async function xlsxToStandardCsv(data: Buffer): Promise<string> {
  const wb = new ExcelJS.Workbook()
  await wb.xlsx.load(data as unknown as ArrayBuffer)
  const ws = wb.getWorksheet("ごみ品目") ?? wb.worksheets[0]
  if (!ws) throw new Error("宇部市Excelにシートがありません")
  const header = EXPECTED_HEADER.map((_, i) =>
    cellText(ws.getRow(1).getCell(i + 1).value).trim()
  )
  if (EXPECTED_HEADER.some((h, i) => header[i] !== h)) {
    throw new Error(
      `宇部市Excelの見出しが想定と違います: ${JSON.stringify(header)}`
    )
  }
  const lines = [HEADER.map(quote).join(",")]
  let id = 0
  for (let r = 2; r <= ws.rowCount; r++) {
    const row = ws.getRow(r)
    const cell = (c: number) => cellText(row.getCell(c).value)
    const rawName = cell(1).trim()
    const rawLabel = cell(4)
    if (!rawName && !rawLabel.trim() && !cell(5).trim()) continue // 空行
    const name = cleanName(rawName)
    if (NOT_ITEMS.has(name)) continue
    const label = cleanLabel(rawLabel)
    if (!name || !label || label === "不明") {
      throw new Error(
        `宇部市Excelの${r}行目: 品目名か区分が空(または「不明」)です。品目ではない行なら NOT_ITEMS に足してください: ${JSON.stringify([rawName, rawLabel])}`
      )
    }
    const note = cleanNote(cell(5), name)
    id += 1
    lines.push([CITY_CODE, String(id), name, label, note].map(quote).join(","))
  }
  return lines.join("\n") + "\n"
}
