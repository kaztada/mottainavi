const base = createStandardCsvAdapter(ubeCityConfig)
const XLSX_CACHE = join(CACHE_DIR, "ube-city.xlsx")
const CSV_CACHE = join(CACHE_DIR, "ube-city.csv")

export const ubeCityAdapter: StandardCsvAdapter = {
  ...base,
  async fetchSource({ refresh }) {
    const { data, fromCache } = await fetchBinaryWithCache(
      readSource("ube-city").file_url,
      XLSX_CACHE,
      refresh
    )
    const source = await xlsxToStandardCsv(data)
    await writeFile(CSV_CACHE, source, "utf-8")
    return { source, fromCache, location: XLSX_CACHE }
  },
  parse: (source) => parseStandardCsv(ubeCityConfig, source),
}
