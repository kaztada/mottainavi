const base = createStandardCsvAdapter(zamaCityConfig)
const XLSX_CACHE = join(CACHE_DIR, "zama-city.xlsx")
const CSV_CACHE = join(CACHE_DIR, "zama-city.csv")

export const zamaCityAdapter: StandardCsvAdapter = {
  ...base,
  async fetchSource({ refresh }) {
    const { data, fromCache } = await fetchBinaryWithCache(
      readSource("zama-city").file_url,
      XLSX_CACHE,
      refresh
    )
    const source = await xlsxToStandardCsv(data)
    await writeFile(CSV_CACHE, source, "utf-8")
    return { source, fromCache, location: XLSX_CACHE }
  },
  parse: (source) => parseStandardCsv(zamaCityConfig, source),
}
